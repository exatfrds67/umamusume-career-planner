    /**
     * Create aptitude records for a character.
     */
    private function createAptitudes(Character $character, array $aptitudes): void
    {
        $aptitudeRecords = [];

        // Distance/Surface combinations
        foreach (['turf', 'dirt'] as $surface) {
            foreach (['short', 'mile', 'medium', 'long'] as $distance) {
                $key = "{$surface}_{$distance}";
                if (isset($aptitudes[$key])) {
                    $aptitudeRecords[] = [
                        'character_id' => $character->id,
                        'distance_type' => $distance,
                        'surface_type' => $surface,
                        'running_style' => null,
                        'grade' => $aptitudes[$key],
                        'created_at' => now(),
                        'updated_at' => now(),
                    ];
                }
            }
        }

        // Running styles
        foreach (['runner', 'leader', 'betweener', 'chaser'] as $style) {
            if (isset($aptitudes[$style])) {
                $aptitudeRecords[] = [
                    'character_id' => $character->id,
                    'distance_type' => null,
                    'surface_type' => null,
                    'running_style' => $style,
                    'grade' => $aptitudes[$style],
                    'created_at' => now(),
                    'updated_at' => now(),
                ];
            }
        }

        // Bulk insert aptitudes
        if (! empty($aptitudeRecords)) {
            /** @var \Illuminate\Database\Eloquent\Builder<\App\Models\Aptitude> $insertQuery */
            $insertQuery = Aptitude::query();
            $insertQuery->insert($aptitudeRecords);
        }
    }
