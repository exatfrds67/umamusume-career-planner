    /**
     * Official aptitude data for characters (from game data)
     * Format: [character_name => [aptitude_type => grade]]
     */
    private array $aptitudeData = [];

    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        // Get or create test user
        $user = User::firstOrCreate(
            ['email' => 'test@example.com'],
            [
                'name' => 'Test User',
                'password' => bcrypt('password'),
            ]
        );

        // Build local image map
        $this->buildLocalImageMap();

        $resolver = app(CharacterGameDataResolver::class);

        // Load official aptitude data
        $this->loadAptitudeData();

        // Fetch character data from umapyoi.net API
        $response = Http::timeout(30)->get('https://api.umapyoi.net/api/v1/character/info');

        if (! $response->successful()) {
            Log::error('Failed to fetch Uma Musume character data from API');
            $this->command->error('Failed to fetch character data from umapyoi.net API');

            return;
        }

        $characters = $response->json();

        // Filter for English global server characters only (those with name_en)
        $englishCharacters = collect($characters)->filter(function ($char) {
            return ! empty($char['name_en']);
        });

        $this->command->info("Found {$englishCharacters->count()} English global server characters");
        $this->command->info("Found {$this->localImageMap->count()} local character images");

        $created = 0;
        $skipped = 0;
        $withLocalImage = 0;
        $withAptitudes = 0;

        DB::beginTransaction();

        try {
            foreach ($englishCharacters as $charData) {
                $characterName = $charData['name_en'];
                $normalizedName = $this->normalizeCharacterName($characterName);
                $gameCharacter = $resolver->findByCharacterName($characterName);

                // Check if character already exists — try exact name first,
                // then fall back to a variant with U+00A0 before the last word,
                // to handle legacy DB rows like "T.M. Opera\u{00A0}O" or
                // "Sakura Bakushin\u{00A0}O".
                /** @var \Illuminate\Database\Eloquent\Builder<\App\Models\Character> $charQuery */
                $charQuery = Character::query();
                $character = $charQuery
                    ->where('user_id', '=', $user->id)
                    ->where('name', '=', $characterName)
                    ->first();

                if (! $character && str_contains($characterName, ' ')) {
                    $lastSpacePos = strrpos($characterName, ' ');
                    $nbspVariant = substr($characterName, 0, $lastSpacePos)."\u{00A0}".substr($characterName, $lastSpacePos + 1);
                    /** @var \Illuminate\Database\Eloquent\Builder<\App\Models\Character> $nbspQuery */
                    $nbspQuery = Character::query();
                    $character = $nbspQuery
                        ->where('user_id', '=', $user->id)
                        ->where('name', '=', $nbspVariant)
                        ->first();
                }

                if ($character) {
                    /** @var \App\Models\Character $character */
                    // Update existing character with aptitudes if we have data and they don't have aptitudes yet
                    if (isset($this->aptitudeData[$normalizedName])) {
                        /** @var \Illuminate\Database\Eloquent\Builder<\App\Models\Aptitude> $aptQuery */
                        $aptQuery = Aptitude::query();
                        $existingAptitudes = $aptQuery->where('character_id', '=', $character->id)->count();
                        if ($existingAptitudes === 0) {
                            $this->createAptitudes($character, $this->aptitudeData[$normalizedName]);
                            $withAptitudes++;
                        }
                    }

                    // Fix broken external avatar URLs when a local image is now available
                    if (
                        $this->localImageMap->has($characterName)
                        && ! str_starts_with((string) $character->avatar_url, '/images/')
                    ) {
                        /** @var \Illuminate\Database\Eloquent\Builder<\App\Models\Character> $avatarQuery */
                        $avatarQuery = Character::query();
                        $avatarQuery->where('id', '=', $character->id)->update(['avatar_url' => $this->localImageMap->get($characterName)]);
                    }

                    // Always refresh current_stats and growth_rates from latest game data
                    /** @var \Illuminate\Database\Eloquent\Builder<\App\Models\Character> $statsQuery */
                    $statsQuery = Character::query();
                    $statsQuery->where('id', '=', $character->id)->update([
                        'current_stats' => json_encode($this->getBaseStats($normalizedName)),
                        'growth_rates' => json_encode($this->getGrowthRates($normalizedName)),
                        'game_character_id' => $character->game_character_id ?? $gameCharacter?->id,
                    ]);

                    $skipped++;

                    continue;
                }

                // Get avatar URL - prefer local image, fallback to API image
                $avatarUrl = $this->getAvatarUrl($charData);
                if (Str::startsWith($avatarUrl, '/images/trainee_images/')) {
                    $withLocalImage++;
                }

                // Create character with official baseline values
                $character = Character::create([
                    'uuid' => Str::uuid()->toString(),
                    'user_id' => $user->id,
                    'name' => $characterName,
                    'avatar_url' => $avatarUrl,
                    'game_character_id' => $gameCharacter?->id,
                    'scenario_type' => 'ura_finale',
                    'career_stage' => 'junior',
                    'current_turn' => 1,
                    'current_stats' => $this->getBaseStats($normalizedName),
                    'stat_priorities' => [
                        'speed' => 5,
                        'stamina' => 4,
                        'power' => 3,
                        'guts' => 2,
                        'wit' => 1,
                    ],
                    'stat_breakpoints' => [],
                    'energy_level' => 100,
                    'mood_status' => 'normal',
                    'conditions' => [],
                    'days_until_race' => null,
                    'goals' => [
                        'target_stats' => [
                            'speed' => 1200,
                            'stamina' => 1000,
                            'power' => 1000,
                            'guts' => 800,
                            'wit' => 1000,
                        ],
                    ],
                    'race_schedule' => [],
                    'training_plan' => [],
                    'growth_rates' => $this->getGrowthRates($normalizedName),
                    'inherited_factors' => [],
                    'legacy_parents' => [],
                    'team_composition' => [],
                    'facility_levels' => [],
                    'spirit_burst_data' => [],
                    'status' => 'active',
                    'completion_data' => [],
                    'available_sp' => 0,
                ]);

                // Create aptitude records if we have data for this character
                if (isset($this->aptitudeData[$normalizedName])) {
                    $this->createAptitudes($character, $this->aptitudeData[$normalizedName]);
                    $withAptitudes++;
                }

                $created++;
            }

            DB::commit();

            $this->command->info("Successfully created {$created} characters");
            $this->command->info("Using local images for {$withLocalImage} characters");
            $this->command->info("Created aptitudes for {$withAptitudes} characters");
            if ($skipped > 0) {
                $this->command->info("Skipped {$skipped} existing characters");
            }
        } catch (\Exception $e) {
            DB::rollBack();
            Log::error('Failed to seed characters', ['error' => $e->getMessage()]);
            $this->command->error("Failed to seed characters: {$e->getMessage()}");
        }
    }

    /**
     * Build a map of character names to local image files.
     */
    private function buildLocalImageMap(): void
    {
        $imagePath = base_path('images/trainee_images');

        if (! File::exists($imagePath)) {
            $this->localImageMap = collect();

            return;
        }

        $files = File::files($imagePath);

        $this->localImageMap = collect($files)->mapWithKeys(function ($file) {
            $filename = $file->getFilename();

            // Extract character name from filename (format: __character_name_umamusume_...)
            if (preg_match('/^__([a-z_]+)_umamusume/', $filename, $matches)) {
                $characterSlug = $matches[1];

                // Convert slug to proper name format
                $characterName = $this->slugToName($characterSlug);

                return [$characterName => '/images/trainee_images/'.$filename];
            }

            return [];
        })->filter();

        // Manual overrides for image files with non-standard naming conventions.
        $manualOverrides = [
            'bb962aabeafaee5cbf7831e4d178ca64.jpg' => 'Silence Suzuka',
        ];

        foreach ($manualOverrides as $filename => $characterName) {
            $fullPath = $imagePath.DIRECTORY_SEPARATOR.$filename;
            if (File::exists($fullPath)) {
                $this->localImageMap->put($characterName, '/images/trainee_images/'.$filename);
            }
        }
    }

