/**
 * Enhanced Real Uma Musume Characters Seeder
 *
 * Seeds all English global server characters with:
 * - Basic character data from umapyoi.net API
 * - Official aptitude grades for all distance/surface/style combinations
 * - Baseline stats and growth rates
 * - Local images where available
 */
